import { afterEach, describe, expect, it, jest } from '@jest/globals';
import { DoImmediateAction, type AppearanceActionContext, type AssetFrameworkGlobalState } from 'pandora-common';
import type { IClientShardArgument } from 'pandora-common/networking/api/shard_client';
import type { Character } from '../src/character/character.ts';
import type { ClientConnection } from '../src/networking/connection_client.ts';
import { ConnectionManagerClient } from '../src/networking/manager_client.ts';
import { Space } from '../src/spaces/space.ts';

afterEach(() => {
	jest.restoreAllMocks();
});

describe('Shard request handling', () => {
	it('deduplicates targets and does not re-send unchanged status', () => {
		const sendMessage = jest.fn();
		const target = { connection: { sendMessage } };
		const space = {
			status: new Map(),
			getCharacterById: () => target,
			sendMessage: jest.fn(),
		} as unknown as Space;
		const character = { id: 'c1' } as unknown as Character;
		Space.prototype.updateStatus.call(space, character, 'typing', ['c2', 'c3', 'c2']);
		Space.prototype.updateStatus.call(space, character, 'typing', ['c3', 'c2']);
		expect(sendMessage).toHaveBeenCalledTimes(2);
	});

	it('bounds permission prompts from one character', async () => {
		const sendMessage = jest.fn();
		const permission = {
			checkPermission: () => 'yes',
			setup: { group: 'interaction', id: 'test', displayName: 'Test' },
			getConfig: () => null,
		};
		const target = { connection: { sendMessage }, gameLogicCharacter: { getPermission: () => permission } };
		const space = { getCharacterById: () => target };
		const character = { getOrLoadSpace: () => space, gameLogicCharacter: {} } as unknown as Character;
		const connection = { character } as unknown as ClientConnection;
		const request: IClientShardArgument['requestPermission'] = { target: 'c2', permissions: [['interaction', 'test']] };

		for (let i = 0; i < 16; i++) {
			expect(await ConnectionManagerClient.onMessage('requestPermission', request, connection)).toEqual({ result: 'promptSent' });
		}
		expect(await ConnectionManagerClient.onMessage('requestPermission', request, connection)).toEqual({ result: 'failure' });
		expect(sendMessage).toHaveBeenCalledTimes(16);
	});

	it('bounds permission prompts generated by game actions', async () => {
		jest.spyOn(Date, 'now').mockReturnValue(1000);
		const state: AssetFrameworkGlobalState = {
			assetManager: {},
			produceCharacterState: (_id: unknown, producer: (value: { produceWithPose: () => object; }) => unknown) => {
				producer({ produceWithPose: () => ({}) });
				return state;
			},
			runAutomaticActions: () => state,
			validate: () => ({ success: true }),
		} as unknown as AssetFrameworkGlobalState;
		const restrictionManager = {
			appearance: { id: 'c1' },
			getModifierEffectProperties: () => [],
			checkInteractWithTarget: (processingContext: { addRestriction: (restriction: unknown) => void; }) => {
				processingContext.addRestriction({
					type: 'missingPermission',
					target: 'c2',
					permissionGroup: 'interaction',
					permissionId: 'interact',
					permissionDescription: 'Interact',
					permissionResult: 'prompt',
				});
			},
		};
		const context = {
			player: { id: 'c1' },
			getCharacter: (id: string) => id === 'c1'
				? { getRestrictionManager: () => restrictionManager }
				: { getAppearance: () => ({ type: 'character' }) },
		};
		const action = { type: 'pose', target: 'c2', view: 'back' } as const;
		const preflight = DoImmediateAction(action, context as unknown as AppearanceActionContext, state);
		expect(preflight.valid).toBe(false);
		if (preflight.valid)
			throw new Error('Expected a promptable action failure');
		expect(preflight.prompt).toBe('c2');

		const sendMessage = jest.fn();
		const space = { currentState: state, getCharacterById: () => ({ connection: { sendMessage } }) };
		const character = { getOrLoadSpace: () => space, getAppearanceActionContext: () => context } as unknown as Character;
		const connection = { character } as unknown as ClientConnection;
		const request: IClientShardArgument['gameLogicAction'] = { operation: 'doImmediately', action };
		for (let i = 0; i < 16; i++) {
			expect(await ConnectionManagerClient.onMessage('gameLogicAction', request, connection)).toEqual({ result: 'promptSent' });
		}
		expect(await ConnectionManagerClient.onMessage('gameLogicAction', request, connection)).toMatchObject({ result: 'failure' });
		expect(sendMessage).toHaveBeenCalledTimes(16);
	});

	it('does not force full reloads after failed game actions', async () => {
		let now = 1000;
		jest.spyOn(Date, 'now').mockImplementation(() => now);
		const sendLoadMessage = jest.fn();
		const state = { assetManager: {}, produceCharacterState: () => null };
		const space = { currentState: state, getCharacterById: jest.fn() };
		const restrictionManager = { appearance: { id: 'c1' } };
		const context = { player: { id: 'c1' }, getCharacter: () => ({ getRestrictionManager: () => restrictionManager }) };
		const character = { getOrLoadSpace: () => space, getAppearanceActionContext: () => context } as unknown as Character;
		const connection = { character, sendLoadMessage } as unknown as ClientConnection;

		for (let i = 0; i < 9; i++) {
			expect(await ConnectionManagerClient.onMessage('gameLogicAction', { operation: 'complete' }, connection)).toMatchObject({ result: 'failure' });
		}
		expect(sendLoadMessage).not.toHaveBeenCalled();
		now += 2_000;
		await ConnectionManagerClient.onMessage('gameLogicAction', { operation: 'complete' }, connection);
		expect(sendLoadMessage).not.toHaveBeenCalled();
	});
});
